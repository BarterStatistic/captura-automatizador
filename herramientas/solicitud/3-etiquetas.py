def refine(txt,x0,x1,ya,yb,peso=600):
    X0,X1,Y0,Y1=x0-4,x1+4,ya-2,yb+2
    r=t[Y0:Y1+1,X0:X1+1]
    ys=np.where(r.any(1))[0]; xs=np.where(r.any(0))[0]
    if len(xs)==0: raise SystemExit('vacio '+txt)
    bx0,bx1=X0+xs.min(),X0+xs.max()
    rows=r.sum(1); mx=rows.max()
    body=np.where(rows>=0.3*mx)[0]
    base=Y0+body.max(); top=Y0+body.min()
    return dict(t=txt,x0=int(bx0),x1=int(bx1),b=int(base),h=int(base-top+1),p=peso)

T=[]
def L(row_ya,row_yb,*items,peso=600):
    for it in items:
        txt,x0,x1=it
        T.append(refine(txt,x0,x1,row_ya,row_yb,peso))

